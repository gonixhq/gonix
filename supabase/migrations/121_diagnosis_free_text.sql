-- visits.icd10_primary มี FK → icd10(code) จึงเก็บข้อความอิสระไม่ได้
-- เพิ่มคอลัมน์ diagnosis_text ให้หมอพิมพ์คำวินิจฉัยเองได้ (ใช้คู่/แทน ICD)
--   • มีรหัส ICD → icd10_primary (เหมือนเดิม)
--   • ไม่มีในรหัส → diagnosis_text (พิมพ์เอง)
-- ════════════════════════════════════════════════════════════

ALTER TABLE visits ADD COLUMN IF NOT EXISTS diagnosis_text text;
COMMENT ON COLUMN visits.diagnosis_text IS 'คำวินิจฉัยแบบพิมพ์เอง (free-text) — ใช้เมื่อโรคไม่มีในรหัส ICD-10';
